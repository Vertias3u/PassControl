-- 0084 — Model calls a client reported (subscription mode, Phase 1b).
--
-- A Claude Pro/Max session signs in to Claude Code with the user's own account and
-- talks to Anthropic directly: Anthropic's terms forbid anything that intermediates
-- that login, so the gateway never sees those calls. Claude Code's own telemetry
-- reports each one to the local sidecar, which uploads it here through
-- POST /api/v1/client-events, authenticated as the agent.
--
-- A different kind of fact from `agent_logs`, so a table of its own:
--   * nobody but the client says the call happened: no receipt, nothing signed;
--   * its cost is what the call WOULD have cost on the API. The plan is a flat fee,
--     so it is never money spent, and it is kept in its own unit and name
--     (`reported_cost_usd_micros`) so nothing sums it with `*_microcents` or into a
--     budget;
--   * `agent_logs` rows are receipt-bearing proof (0026) and stay that.
--
-- Since Phase 2 it also holds what an agent's tool rules decided at Claude Code's
-- PreToolUse hook (`kind = 'tool_decision'`): the tool's name, the decision, the rule
-- and how long the owner was waited for (in `duration_ms`). Never the command, path
-- or URL the decision was about, and nothing that is a model call.
--
-- `auth_method` is the credential that UPLOADED the row (invariant 1: a Direct Agent
-- Key is never a passport). The declared fields hold the patterns the sidecar and
-- the gateway hold them to. `event_key` is generated by the sidecar once per event
-- and reused on every retry, so a retried upload is a no-op (`on conflict do
-- nothing`). Anthropic's request id is deliberately not kept.
--
-- Append-only and locked like every tenant table: RLS on, a tenant reads only its
-- own rows, the service role reads and inserts, and nobody updates or deletes a
-- row (deleting the agent or the account removes its rows by cascade). The agent
-- is tied to the tenant by a composite key, so a row can never put one tenant's
-- report on another tenant's agent.
--
-- Kept 90 days (owner, 2026-10-12). A row leaves before its agent or account does
-- only through the two functions below, whose window is fixed inside them, so no
-- caller can choose which recent rows go: the gateway ages an agent's rows out at
-- most once a day after an upload (both deploy modes), and Cloud's daily retention
-- sweep purges every tenant's, so an agent that stopped uploading ages out too.
--
-- Apply before deploying the code that writes it. Until then the endpoint answers
-- that the records are not available, and nothing else changes.

-- The composite key's target. `id` is already the primary key, so this holds by
-- construction; it exists only to be referenced.
create unique index if not exists agents_id_user_id on public.agents (id, user_id);

create table if not exists public.client_reported_calls (
  id                       uuid primary key default gen_random_uuid(),
  user_id                  uuid not null references public.users(id) on delete cascade,
  agent_id                 uuid not null,
  event_key                text not null,
  source                   text not null,
  kind                     text not null,
  auth_method              text not null,
  client_session           text,
  client_agent             text,
  model                    text,
  occurred_at              timestamptz,
  received_at              timestamptz not null default now(),
  input_tokens             bigint,
  output_tokens            bigint,
  cache_read_tokens        bigint,
  cache_creation_tokens    bigint,
  reported_cost_usd_micros bigint,
  duration_ms              bigint,
  status_code              integer,
  tool_name                text,
  decision                 text,
  rule_index               integer,
  constraint client_reported_calls_agent_tenant
    foreign key (agent_id, user_id) references public.agents (id, user_id) on delete cascade,
  constraint client_reported_calls_vocab check (
    source in ('claude_code_otel')
    and kind in ('model_call', 'model_error', 'tool_decision')
    and (decision is null or decision in (
      'deny', 'ask', 'owner_approved', 'owner_denied', 'owner_timeout', 'owner_unavailable', 'rules_invalid'))
    and auth_method in ('passport', 'direct_key')
  ),
  -- `is not null` beside a pattern where the column is required: a NULL fails a
  -- regex as UNKNOWN, and a check constraint lets UNKNOWN through.
  constraint client_reported_calls_fields check (
    event_key is not null and event_key ~ '^[A-Za-z0-9_-]{16,64}$'
    and (client_session is null or client_session ~ '^[A-Za-z0-9._:-]{1,128}$')
    and (client_agent is null or client_agent ~ '^[A-Za-z0-9._:-]{1,128}$')
    and (model is null or model ~ '^[A-Za-z0-9._:/@-]{1,100}$')
    and (tool_name is null or tool_name ~ '^[A-Za-z0-9_.-]{1,128}$')
    and (rule_index is null or rule_index between 0 and 99)
  ),
  constraint client_reported_calls_counts check (
    (input_tokens is null or input_tokens between 0 and 1000000000)
    and (output_tokens is null or output_tokens between 0 and 1000000000)
    and (cache_read_tokens is null or cache_read_tokens between 0 and 1000000000)
    and (cache_creation_tokens is null or cache_creation_tokens between 0 and 1000000000)
    and (reported_cost_usd_micros is null or reported_cost_usd_micros between 0 and 10000000000)
    and (duration_ms is null or duration_ms between 0 and 86400000)
  ),
  -- A cost belongs to a call, a status to an error, a tool and a decision to a tool
  -- decision, which carries nothing about a model.
  constraint client_reported_calls_kind_shape check (
    (kind in ('model_call', 'model_error') and tool_name is null and decision is null and rule_index is null
      and ((kind = 'model_call' and status_code is null)
        or (kind = 'model_error' and reported_cost_usd_micros is null
            and (status_code is null or status_code between 100 and 599))))
    or (kind = 'tool_decision' and tool_name is not null and decision is not null
        and model is null and input_tokens is null and output_tokens is null
        and cache_read_tokens is null and cache_creation_tokens is null
        and reported_cost_usd_micros is null and status_code is null)
  )
);

comment on table public.client_reported_calls is
  'Model calls a client reported (Claude Code telemetry on a Pro/Max login): not proxied, no receipt; the cost is API-equivalent and never spent. Also the tool rules'' decisions at Claude Code''s PreToolUse hook (kind tool_decision): the tool and the decision, never what it was about.';
comment on column public.client_reported_calls.reported_cost_usd_micros is
  'What the call would have cost on the API, as the client reported it, in millionths of a dollar. Never money spent: do not sum with *_microcents.';

-- One row per reported event: a retried upload is a no-op.
create unique index if not exists client_reported_calls_one_per_event
  on public.client_reported_calls (agent_id, event_key);
-- The agent page reads the newest first (filtered by agent, and by tenant through
-- RLS). Leads with the composite foreign key's full column list, in order, which is
-- what covers it: an index that only starts with agent_id does not (Supabase's
-- unindexed_foreign_keys advisor), so a deleted agent's cascade would scan.
create index if not exists client_reported_calls_agent_recent
  on public.client_reported_calls (agent_id, user_id, received_at desc);
-- The users foreign key's own index (Supabase's unindexed_foreign_keys advisor).
create index if not exists client_reported_calls_user_id
  on public.client_reported_calls (user_id);

alter table public.client_reported_calls enable row level security;

-- service_role too: Supabase's defaults grant it everything, and nothing ever
-- updates or deletes a reported row.
revoke all on table public.client_reported_calls from public, anon, authenticated, service_role;
grant select on table public.client_reported_calls to authenticated;
grant select, insert on table public.client_reported_calls to service_role;

drop policy if exists client_reported_calls_select_own on public.client_reported_calls;
create policy client_reported_calls_select_own on public.client_reported_calls
  for select to authenticated
  using (user_id = (select auth.uid()));

-- Retention: this agent's rows received more than 90 days ago, for the tenant that
-- owns it. SECURITY DEFINER because nobody holds DELETE on the table; the window is
-- not a parameter. Returns how many rows went.
create or replace function public.prune_client_reported_calls(p_agent_id uuid, p_user_id uuid)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  removed integer;
begin
  delete from public.client_reported_calls
   where agent_id = p_agent_id
     and user_id = p_user_id
     and received_at < now() - interval '90 days';
  get diagnostics removed = row_count;
  return removed;
end;
$$;

revoke all on function public.prune_client_reported_calls(uuid, uuid) from public, anon, authenticated;
grant execute on function public.prune_client_reported_calls(uuid, uuid) to service_role;

-- Retention across every tenant, for Cloud's daily retention sweep. A sequential
-- scan once a day; no index is kept for it.
create or replace function public.purge_client_reported_calls()
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  removed integer;
begin
  delete from public.client_reported_calls
   where received_at < now() - interval '90 days';
  get diagnostics removed = row_count;
  return removed;
end;
$$;

revoke all on function public.purge_client_reported_calls() from public, anon, authenticated;
grant execute on function public.purge_client_reported_calls() to service_role;
